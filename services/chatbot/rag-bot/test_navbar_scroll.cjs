const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const exportsObject = {};
const source = fs.readFileSync(path.resolve(__dirname, '../../../lib/navbar-scroll-logic.ts'), 'utf8');
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsObject });
const advance = exportsObject.advanceNavbarScroll;
assert.equal(advance({ y: 30, travel: 0 }, 55, 500).hidden, true);
assert.equal(advance({ y: 70, travel: 0 }, 59, 500).hidden, false);
assert.equal(advance({ y: 50, travel: 0 }, 53, 500).hidden, undefined);
assert.equal(advance({ y: 50, travel: 19 }, 54, 500).hidden, true);
assert.equal(advance({ y: 54, travel: 8 }, 49, 500).state.travel, -5);
assert.equal(advance({ y: 30, travel: 0 }, -15, 500).hidden, false);
assert.equal(advance({ y: 500, travel: 0 }, 530, 500).hidden, undefined);
assert.equal(advance({ y: 0, travel: 0 }, 30, -10).hidden, false);
assert.equal(advance({ y: null, travel: 0 }, 100, 500).hidden, undefined);
console.log('Nine navbar direction, jitter, short-list and overscroll checks passed.');
