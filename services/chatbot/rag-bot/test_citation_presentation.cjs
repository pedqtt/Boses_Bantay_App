const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root=path.resolve(process.argv[2]||process.cwd());
const ts=require(path.join(root,'node_modules/typescript'));
const source=fs.readFileSync(path.join(root,'lib/chat/citation-presentation.ts'),'utf8');
const script=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const context={exports:{}};vm.runInNewContext(script,context);
const {unwrapExcerpt,answerBlocks,answerWithoutSourceList,answerForDisplay}=context.exports;
assert.equal(unwrapExcerpt('Residents\nbring\none valid\nID.\n\nPayment is made\nafter validation.'),'Residents bring one valid ID.\n\nPayment is made after validation.');
assert.equal(unwrapExcerpt('Requirements:\n1. Valid ID\n2. Form H-01'),'Requirements:\n1. Valid ID\n2. Form H-01');
assert.equal(unwrapExcerpt('Residents\n\nbring\n\none\n\nvalid\n\nID.\n\nPayment is made after validation.'),'Residents bring one valid ID.\n\nPayment is made after validation.');
assert.equal(unwrapExcerpt('Residents\u2028bring valid ID.\u2029Payment is made after validation.'),'Residents bring valid ID.\n\nPayment is made after validation.');
const original='Residents\n\nbring\n\none\n\nvalid\n\nID.\n\n1. Submit Form H-01\n2. Wait for validation';
assert.equal(unwrapExcerpt(original).replace(/\s+/g,' '),original.replace(/\s+/g,' '));
const citations=[{id:2,documentTitle:'guide.pdf',section:'page 3'}];
assert.equal(answerWithoutSourceList('A fact [2].\n\nSources:\n\n[2] guide.pdf, page 3',citations),'A fact [2].');
assert.equal(answerWithoutSourceList('A fact [2].\n\nPinagmulan:\n\n[2] guide.pdf, page 3',citations),'A fact [2].');
const unexpected='A fact [2].\n\nSources:\n[99] other.pdf';
assert.equal(answerWithoutSourceList(unexpected,citations),unexpected);
assert.equal(answerWithoutSourceList(unexpected,[]),unexpected);
const note='A fact [2].\n\nSources:\n[2] guide.pdf, page 3\nConfirm the date.';
assert.equal(answerWithoutSourceList(note,citations),note);
assert.equal(answerForDisplay('A fact [2].\n\nBack to categories: Menu / Mga Paksa\n\nSources:\n\n[2] guide.pdf, page 3',citations),'A fact [2].');
assert.equal(answerForDisplay('A fact [2].\n\nBumalik sa mga kategorya: Mga Paksa',citations),'A fact [2].');
assert.equal(answerForDisplay('Back to categories: Menu is a navigation label.',[]),'Back to categories: Menu is a navigation label.');
const blocks=answerBlocks('A sentence\nwrapped in a PDF [2].\n\n1. Prepare [2].\n2. Submit [2].\n\nKeep the receipt [2].');
assert.equal(blocks.length,3);assert.equal(blocks[0].text,'A sentence wrapped in a PDF [2].');
assert.equal(blocks[1].kind,'list');assert.equal(blocks[1].rows.length,2);assert.equal(blocks[1].rows[1].label,'2.');
assert.equal(blocks[2].text,'Keep the receipt [2].');
// Exercise the expanded React component, including the excerpt's layout props.
const componentSource=fs.readFileSync(path.join(root,'components/chat/ChatResponse.tsx'),'utf8');
const componentScript=ts.transpileModule(componentSource,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX}}).outputText;
const jsx=(type,props)=>({type,props});
const componentContext={exports:{},require:(name)=>{
  if(name==='react') return {useState:()=>[2,()=>{}]};
  if(name==='react/jsx-runtime') return {jsx,jsxs:jsx};
  if(name==='react-native') return {View:'View',Text:'Text',Pressable:'Pressable'};
  if(name==='@expo/vector-icons') return {Ionicons:'Icon'};
  if(name==='@/lib/theme') return {colors:{}};
  if(name==='@/lib/chat/citation-presentation') return context.exports;
  throw new Error('Unexpected import '+name);
}};
vm.runInNewContext(componentScript,componentContext);
const excerpt='Residents\n\nbring\n\none\n\nvalid\n\nID.';
const rendered=componentContext.exports.ChatResponse({message:{text:'A fact [2].',citations:[{...citations[0],excerpt}]}});
const nodes=[];
function visit(node){if(!node||typeof node!=='object')return;if(Array.isArray(node)){node.forEach(visit);return;}nodes.push(node);visit(node.props?.children);}
visit(rendered);
const excerptNode=nodes.find(node=>node.type==='Text'&&node.props.children==='Residents bring one valid ID.');
assert.ok(excerptNode,'Expanded excerpt is rendered as a normal paragraph');
assert.equal(excerptNode.props.style.width,'100%');
assert.equal(excerptNode.props.style.fontSize,14);
assert.equal(excerptNode.props.style.lineHeight,22);
assert.equal(excerptNode.props.style.flexGrow,0);
assert.ok(nodes.some(node=>node.type==='View'&&node.props.style?.maxWidth===640&&node.props.style.flexGrow===0));
console.log('Citation presentation checks passed: PDF wrapping, source-only tails, unmatched content, and guide layout.');
